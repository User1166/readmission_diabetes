def add_features(df):
    df = df.copy()
    df["prior_visits"] = df[["number_outpatient", "number_emergency", "number_inpatient"]].sum(axis=1)
    drugs = [c for c in DRUG_COLS if c in df.columns]
    df["num_drugs_active"] = (df[drugs] != "No").sum(axis=1)
    return df


