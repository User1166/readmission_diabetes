def summarize(name, y_true, pred, prob=None):
    tn, fp, fn, tp = confusion_matrix(y_true, pred, labels=[0, 1]).ravel()
    n = len(y_true)
    row = {
        "model": name, "n": n, "TP": tp, "FP": fp, "FN": fn, "TN": tn,
        "accuracy": round((tp + tn) / n, 4),
        "recall": round(tp / (tp + fn), 4) if (tp + fn) else 0.0,
        "specificity": round(tn / (tn + fp), 4) if (tn + fp) else 0.0,
        "precision": round(tp / (tp + fp), 4) if (tp + fp) else np.nan,
        "flag_rate": round((tp + fp) / n, 4),
    }
    if prob is not None:
        row["roc_auc"] = round(roc_auc_score(y_true, prob), 4)
        row["pr_auc"] = round(average_precision_score(y_true, prob), 4)
    return row


