# ---------- 1. Cleaning helpers ----------
def age_to_years(s):
    """'[70-80)' -> 75.0. Numeric input passes through unchanged."""
    if isinstance(s, (int, float, np.integer, np.floating)):
        return float(s)
    lo, hi = str(s).strip("[)").split("-")
    return (float(lo) + float(hi)) / 2


def icd_group(code):
    """Group an ICD-9 diagnosis code into its standard chapter."""
    if pd.isna(code):
        return "Missing"
    s = str(code).strip()
    if s.upper().startswith(("V", "E")):
        return "External/Supplementary"
    try:
        v = float(s)
    except ValueError:
        return "Other"
    if 250 <= v < 251:
        return "Diabetes"
    if 390 <= v < 460 or v == 785:
        return "Circulatory"
    if 460 <= v < 520 or v == 786:
        return "Respiratory"
    if 520 <= v < 580 or v == 787:
        return "Digestive"
    if 580 <= v < 630 or v == 788:
        return "Genitourinary"
    if 140 <= v < 240:
        return "Neoplasms"
    if 710 <= v < 740:
        return "Musculoskeletal"
    if 800 <= v < 1000:
        return "Injury"
    return "Other"


def prep_raw(df):
    """Training-only cleaning: converts raw codes into model-ready values."""
    df = df.copy()
    df["age"] = df["age"].map(age_to_years)
    for c in DIAG_COLS:
        df[c] = df[c].map(icd_group)
    for c in ID_AS_CAT:
        df[c] = df[c].astype("Int64").astype(str).replace("<NA>", "Missing")
    return prep_common(df)


def prep_common(df):
    """Applied to training data AND app input: fill and type every field the same way."""
    df = df.copy()
    for c in df.columns:
        if c in NUMERIC_IN_APP:
            df[c] = pd.to_numeric(df[c], errors="coerce")
        else:
            df[c] = df[c].where(df[c].notna(), "Missing").astype(str)
    return df


NUMERIC_IN_APP = ["age", "time_in_hospital", "num_lab_procedures", "num_procedures",
                  "num_medications", "number_outpatient", "number_emergency",
                  "number_inpatient", "number_diagnoses"]


